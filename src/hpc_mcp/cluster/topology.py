class TopologyService:
    """Collect and cache compute-node topology facts."""

    def __init__(
        self,
        cfg: Config,
        files: FileService,
        safe_exec: SafeExec,
        slurm: SlurmManager,
    ) -> None:
        self._cfg = cfg
        self._files = files
        self._safe_exec = safe_exec
        self._slurm = slurm
        self._lock = asyncio.Lock()
        self._memory: dict[str, tuple[float, dict[str, Any]]] = {}
        self._pending: dict[str, dict[str, Any]] = {}

    # -- public API -----------------------------------------------------------

    async def probe(self, *, partition: str | None = None, refresh: bool = False) -> dict[str, Any]:
        """Return topology facts for ``partition`` (cached when fresh)."""
        async with self._lock:
            part = self._resolve_partition(partition)
            ttl = float(self._cfg.topology.cache_ttl_seconds)
            if not refresh:
                hit = self._memory_lookup(part, ttl)
                if hit is not None:
                    payload, age = hit
                    return {**payload, "source": "session-cache", "cache_age_seconds": round(age, 1)}
                remote = await self._remote_cache_lookup(part, ttl)
                if remote is not None:
                    self._memory_put(part, remote)
                    return {**remote, "source": "remote-cache"}
            else:
                await self._drop_pending(part, cancel=True)

            pending = self._pending.get(part)
            if pending is not None and not refresh:
                resumed = await self._resume_pending(part, pending)
                if resumed is not None:
                    return resumed
            return await self._collect(part)

    def invalidate(self) -> None:
        """Drop in-process caches (called after agent-driven reconfiguration)."""
        self._memory.clear()

    # -- internals ------------------------------------------------------------

    def _resolve_partition(self, partition: str | None) -> str:
        allowed = self._cfg.slurm.allowed_partitions
        if not allowed:
            raise SlurmPolicyError(
                "No Slurm partitions are allowed by the server configuration, so no compute node "
                "can be probed. Ask the administrator to set slurm.allowed_partitions (fail-closed default)."
            )
        if partition is None:
            # The configured default goes through the same identifier check as
            # a requested one: the name is interpolated into ``sinfo -p`` and
            # into the cache filename, so a hand-edited config must not be able
            # to smuggle anything in (fail-closed).
            partition = allowed[0]
        if not isinstance(partition, str) or not _SAFE_PARTITION_RE.match(partition):
            raise SlurmPolicyError(
                "Partition must be a simple name (letters, digits, '.', '-', '_')",
                requested="(redacted)",
            )
        if partition not in allowed:
            raise SlurmPolicyError(
                "Requested partition is not allowed by the server policy",
                requested="(redacted)",
            )
        return partition

    @property
    def _topo_dir(self) -> str:
        return f"{self._cfg.root.rstrip('/')}/{TOPO_DIRNAME}"

    @property
    def _script_path(self) -> str:
        return f"{self._topo_dir}/{PROBE_SCRIPT_NAME}"

    def _cache_path(self, partition: str) -> str:
        safe = re.sub(r"[^A-Za-z0-9_.-]", "_", partition)[:64]
        return f"{self._topo_dir}/topology_{safe}.json"

    def _memory_lookup(self, partition: str, ttl: float) -> tuple[dict[str, Any], float] | None:
        entry = self._memory.get(partition)
        if not entry:
            return None
        stored_at, payload = entry
        age = time.time() - stored_at
        if ttl <= 0 or age > ttl:
            self._memory.pop(partition, None)
            return None
        return payload, age

    def _memory_put(self, partition: str, payload: dict[str, Any]) -> None:
        if self._cfg.topology.cache_ttl_seconds <= 0:
            return
        # The stored entry must not carry a snapshot of the age it had when it
        # was first served; the age is recomputed from ``stored_at`` instead.
        clean = {key: value for key, value in payload.items() if key != "cache_age_seconds"}
        self._memory[partition] = (time.time(), clean)

    async def _drop_pending(self, partition: str, *, cancel: bool) -> None:
        """Forget a queued probe job, optionally cancelling it first.

        Only jobs this service itself submitted can ever be in ``_pending``,
        so cancelling one is safe under a shared account.
        """
        entry = self._pending.pop(partition, None)
        if not entry or not cancel:
            return
        try:
            await self._slurm.cancel(str(entry.get("job_id")))
        except HpcMcpError:
            pass

    async def _remote_cache_lookup(self, partition: str, ttl: float) -> dict[str, Any] | None:
        if ttl <= 0:
            return None
        try:
            read = await self._files.read_file(self._cache_path(partition), max_bytes=256 * 1024)
        except HpcMcpError:
            return None
        except Exception:  # noqa: BLE001 - a missing/corrupt cache is not an error
            return None
        try:
            payload = json.loads(read.get("content") or "")
        except ValueError:
            return None
        if not isinstance(payload, dict) or payload.get("status") != "ok":
            return None
        if payload.get("partition") != partition:
            return None
        collected = payload.get("collected_at_epoch")
        if not isinstance(collected, (int, float)) or isinstance(collected, bool):
            return None
        age = time.time() - float(collected)
        if age < 0 or age > ttl:
            return None
        payload = dict(payload)
        payload["cache_age_seconds"] = round(age, 1)
        return payload

    async def _write_remote_cache(self, partition: str, payload: dict[str, Any]) -> None:
        if self._cfg.topology.cache_ttl_seconds <= 0:
            return
        try:
            await self._files.write_file(self._cache_path(partition), json.dumps(payload, ensure_ascii=False))
        except HpcMcpError:
            # A cache that cannot be persisted is not worth failing the probe.
            return

    async def _write_probe_script(self) -> None:
        await self._files.mkdir(self._topo_dir, parents=True)
        await self._files.write_file(self._script_path, PROBE_SCRIPT)

    async def _query_sinfo(self) -> dict[str, Any]:
        """Partition summary plus distinct per-node hardware variants."""
        configured = list(self._cfg.slurm.allowed_partitions)
        # Partition names end up inside ``sinfo -p`` (comma list), so keep only
        # plain identifiers; anything else is reported, never interpolated.
        allowed = [p for p in configured if isinstance(p, str) and _SAFE_PARTITION_RE.match(p)]
        rejected = [p for p in configured if p not in allowed]
        result: dict[str, Any] = {"available": False, "partitions": [], "node_variants": []}
        if rejected:
            result["error"] = (
                f"{len(rejected)} configured partition name(s) are not plain identifiers and were ignored"
            )
        if not allowed:
            return result
        summary = await self._safe_exec.run(f'sinfo -h -o "{SINFO_PARTITION_FORMAT}"')
        if summary.get("exit_code") != 0:
            result["error"] = (summary.get("stderr") or "").strip()[:500] or "sinfo failed"
            return result
        rows = parse_sinfo_partitions(summary.get("stdout") or "")
        result["partitions"] = [row for row in rows if row["partition"] in allowed]
        query = ",".join(allowed)
        nodes = await self._safe_exec.run(f'sinfo -h -N -p {query} -o "{SINFO_NODE_FORMAT}"')
        if nodes.get("exit_code") == 0:
            variants, rows_seen = parse_sinfo_nodes(nodes.get("stdout") or "")
            result["node_variants"] = variants[:8]
            result["node_rows_seen"] = rows_seen
        result["available"] = True
        return result

    def _sinfo_for(self, sinfo: dict[str, Any], partition: str) -> dict[str, Any] | None:
        for row in sinfo.get("partitions", []):
            if row.get("partition") == partition:
                return row
        return None

    async def _collect(self, partition: str) -> dict[str, Any]:
        sinfo = await self._query_sinfo()
        await self._write_probe_script()
        submitted = await self._slurm.submit(
            job_name=PROBE_JOB_NAME,
            working_directory=self._topo_dir,
            command=["bash", self._script_path],
            partition=partition,
            nodes=1,
            ntasks=1,
            cpus_per_task=1,
            time_limit=self._cfg.topology.collect_time_limit,
        )
        job_id = str(submitted["job_id"])
        try:
            state = await self._slurm.wait(
                job_id,
                timeout_seconds=self._cfg.topology.wait_seconds,
                poll_interval=5,
            )
        except RemoteCommandError:
            self._pending[partition] = {"job_id": job_id, "started": time.monotonic()}
            return {
                "status": "pending",
                "partition": partition,
                "collection_job_id": job_id,
                "job_dir": submitted.get("job_dir"),
                "note": (
                    f"拓扑采集作业 {job_id} 已提交但仍在排队（等待 "
                    f"{self._cfg.topology.wait_seconds}s 未完成）。稍后再次调用会复用它，不会重复提交。"
                ),
                "sinfo": self._sinfo_block(sinfo, partition),
            }
        return await self._finalize(partition, job_id, state, sinfo)

    async def _resume_pending(self, partition: str, pending: dict[str, Any]) -> dict[str, Any] | None:
        """Re-check a queued probe job.  None means "give up and re-collect"."""
        job_id = str(pending.get("job_id"))
        age = time.monotonic() - float(pending.get("started", 0.0))
        try:
            status = await self._slurm.status(job_id)
        except HpcMcpError:
            await self._drop_pending(partition, cancel=False)
            return None
        state = str(status.get("state", "UNKNOWN")).split("+")[0].strip()
        if state in _OK_STATES or state in _BAD_STATES:
            await self._drop_pending(partition, cancel=False)
            sinfo = await self._query_sinfo()
            return await self._finalize(partition, job_id, {"state": state}, sinfo)
        if age > max(60.0, self._cfg.topology.wait_seconds * 4):
            # Give up on a job that has been queued for far too long; free the
            # slot.  Only this service's own probe jobs can reach this path.
            await self._drop_pending(partition, cancel=True)
            return None
        return {
            "status": "pending",
            "partition": partition,
            "collection_job_id": job_id,
            "note": (
                f"拓扑采集作业 {job_id} 仍在队列中（当前状态 {state}，已等待 {round(age)}s）。"
                "稍后再次调用会复用它；如长时间无法调度，请向管理员确认分区可用性。"
            ),
        }

    async def _finalize(
        self,
        partition: str,
        job_id: str,
        state: dict[str, Any],
        sinfo: dict[str, Any],
    ) -> dict[str, Any]:
        final_state = str(state.get("state", "UNKNOWN")).split("+")[0].strip()
        if final_state not in _OK_STATES:
            stderr = ""
            try:
                err = await self._slurm.output(job_id, stream="stderr", tail_bytes=8192)
                stderr = (err.get("content") or "").strip()[:1000]
            except HpcMcpError:
                pass
            raise RemoteCommandError(
                f"Topology probe job {job_id} finished in state {final_state}"
                + (f"; stderr tail: {stderr}" if stderr else "")
                + ". Use hpc.slurm.output / hpc.jobs.diagnose for details."
            )
        out = await self._slurm.output(job_id, tail_bytes=_PROBE_OUTPUT_LIMIT)
        payload = self._build_payload(partition, job_id, out.get("content") or "", sinfo)
        await self._write_remote_cache(partition, payload)
        self._memory_put(partition, payload)
        return {**payload, "source": "probe-job"}

    def _sinfo_block(self, sinfo: dict[str, Any], partition: str) -> dict[str, Any]:
        return {
            "available": bool(sinfo.get("available")),
            "partition": self._sinfo_for(sinfo, partition),
            "node_variants": sinfo.get("node_variants", []),
            "error": sinfo.get("error"),
        }

    def _build_payload(
        self,
        partition: str,
        job_id: str,
        stdout: str,
        sinfo: dict[str, Any],
    ) -> dict[str, Any]:
        sections = split_sections(stdout)
        cpu = parse_lscpu(sections.get("lscpu", ""))
        cpuinfo = parse_cpuinfo(sections.get("cpuinfo", ""))
        numactl = parse_numactl(sections.get("numactl", ""))
        meminfo = parse_meminfo(sections.get("meminfo", ""))
        syscache = parse_sysfs_cache(sections.get("syscache", ""))
        meta = _env_lines(sections.get("meta", ""))
        os_lines = [line.strip() for line in (sections.get("os", "") or "").splitlines() if line.strip()]

        if not cpu or (cpu.get("model_name") is None and cpu.get("logical_cpus") is None):
            # lscpu absent: salvage what /proc/cpuinfo knows.
            cpu = {
                "model_name": cpuinfo.get("model_name"),
                "vendor": cpuinfo.get("vendor"),
                "sockets": None,
                "cores_per_socket": cpuinfo.get("cpu_cores"),
                "threads_per_core": None,
                "physical_cores": None,
                "logical_cpus": cpuinfo.get("siblings"),
                "numa_nodes": None,
                "numa_cpu_lists": {},
                "cache_kib": {},
                "cache_raw": {},
                "flags": cpuinfo.get("flags"),
            }
        cpu["simd"] = summarize_simd(cpu.get("flags"))
        cpu.pop("flags", None)  # the raw flag list is long and not needed twice

        # Cache hierarchy: lscpu is authoritative when it says something;
        # otherwise fall back to /sys (older lscpu builds, many ARM nodes).
        lscpu_cache = cpu.get("cache_kib") or {}
        if any(value for value in lscpu_cache.values()):
            cpu["cache_source"] = "lscpu"
        elif syscache:
            cpu["cache_kib"] = {**{key: None for key in ("l1d", "l1i", "l2", "l3")}, **syscache}
            cpu["cache_source"] = "sysfs"
        else:
            cpu["cache_source"] = None

        numa = {
            "count": numactl.get("count") or cpu.get("numa_nodes"),
            "nodes": numactl.get("nodes") or [
                {"node": int(node), "cpus": spec, "cpus_count": count_cpu_list(spec)}
                for node, spec in (cpu.get("numa_cpu_lists") or {}).items()
            ],
            "distances": numactl.get("distances") or [],
            "source": "numactl" if numactl else ("lscpu" if cpu.get("numa_cpu_lists") else None),
        }

        partition_row = self._sinfo_for(sinfo, partition)
        recommended = recommend_parallel(
            cpu,
            numa,
            meminfo,
            sinfo_partition=partition_row,
            slurm_max_cpus=self._cfg.slurm.max_cpus,
            slurm_max_nodes=self._cfg.slurm.max_nodes,
            slurm_max_time=self._cfg.slurm.max_time,
        )

        notes: list[str] = []
        variants = sinfo.get("node_variants") or []
        if len(variants) > 1:
            notes.append(
                f"该分区的节点不是同构的（{len(variants)} 种硬件组合）：拓扑只代表采样节点 "
                f"{meta.get('SLURMD_NODENAME') or 'unknown'}，用 --constraint 或按节点提交可避免落到不同型号上。"
            )
        if not sections.get("lscpu") or "unavailable lscpu" in (sections.get("lscpu") or ""):
            notes.append("计算节点上没有 lscpu，部分字段来自 /proc/cpuinfo，可能不如 lscpu 完整。")
        if not cpu.get("cache_source"):
            notes.append(
                "该节点没有可用的 cache 层级信息（lscpu 未输出 cache 行，"
                "/sys/devices/system/cpu/cpu0/cache 也不可读）——cache 分块与共享域相关的调优请靠实测确定。"
            )
        if sinfo.get("error"):
            notes.append(f"sinfo 查询失败，Slurm 侧信息缺失：{sinfo['error']}")
        if partition_row and partition_row.get("features") is None:
            notes.append(
                "该分区没有配置 node features（sinfo 显示为空），因此无法用 --constraint 按微架构选节点；"
                "扩容到异构分区时请显式指定节点或向管理员申请 features 标签。"
            )

        return {
            "status": "ok",
            "partition": partition,
            "collected_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "collected_at_epoch": time.time(),
            "collection_job_id": job_id,
            "collected_on_node": meta.get("SLURMD_NODENAME"),
            "cpu": cpu,
            "numa": numa,
            "cache_kib": cpu.get("cache_kib"),
            "memory_mib": {
                "mem_total": meminfo.get("memtotal"),
                "mem_free": meminfo.get("memfree"),
                "mem_available": meminfo.get("memavailable"),
                "hugepage_size": meminfo.get("hugepagesize"),
            },
            "os": {
                "system": os_lines[0] if len(os_lines) > 0 else None,
                "machine": os_lines[1] if len(os_lines) > 1 else None,
                "kernel": os_lines[2] if len(os_lines) > 2 else None,
            },
            "slurm": {
                **self._sinfo_block(sinfo, partition),
                "node_rows_seen": sinfo.get("node_rows_seen"),
            },
            "job_environment": {
                "cpus_on_node": _as_int(meta.get("SLURM_CPUS_ON_NODE")),
                "mem_per_node_mb": _as_int(meta.get("SLURM_MEM_PER_NODE")),
            },
            "recommended_parallel_parameters": recommended,
            "notes": notes,
        }
