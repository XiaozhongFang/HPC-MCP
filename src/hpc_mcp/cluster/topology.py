"""Compute-node topology discovery for parallel-optimization decisions.

``hpc.cluster.topo`` answers the question the login-node whitelist
deliberately cannot: *what hardware will my job actually run on?*  CPU model,
sockets/cores/threads, SIMD capability, NUMA domains, cache hierarchy and
node memory -- the facts needed to pick ``--ntasks-per-node``,
``--cpus-per-task``, MPI binding and ``OMP_NUM_THREADS``.

Two data sources are combined:

* ``sinfo`` on the login node (already whitelisted, LOW cost tier): partition
  sizes, CPUs/memory per node, features and GRES -- Slurm's own view, no job
  needed.
* a **fixed, server-generated** probe script run as a tiny one-CPU job on a
  compute node: ``lscpu`` / ``/proc/cpuinfo`` / ``numactl --hardware`` /
  ``/proc/meminfo``.  The agent supplies *no part* of that script, and the
  script never calls ``squeue``/``sacct``/``scontrol``: only node-local
  hardware facts are read, so no other user's job metadata can reach this
  process (the same shared-account isolation rule that forbids those tools on
  the login node).

Results are cached twice: in-process for this session, and remotely as a JSON
file under ``$ROOT/.hpc-mcp/topo/`` so later sessions re-use a static hardware
probe instead of queueing another job.  ``refresh=true`` forces a re-probe.
"""

